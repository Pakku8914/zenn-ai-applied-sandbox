I = tuple[str, float, str]


def P(name: str, preset: str, category: str, mains: list[I], *, extra: list[I] | None = None,
      tags: tuple[str, ...] = (), servings: int = 2, minutes: int | None = None) -> dict:
    cuisine, base, seasonings, steps = PRESETS[preset]
    a = mains[0][0]
    b = "と".join(m[0] for m in mains[1:]) or a
    return {
        "name": name, "cuisine": cuisine, "category": category, "minutes": minutes or base,
        "servings": servings, "ingredients": [*mains, *(extra or []), *seasonings],
        "steps": [s.format(a=a, b=b, all="と".join(m[0] for m in mains)) for s in steps if not ("{b}" in s and len(mains) == 1 and s.startswith("{b}"))],
        "extra_tags": list(tags),
    }


def C(name: str, cuisine: str, category: str, minutes: int, ingredients: list[I], steps: list[str], *,
      tags: tuple[str, ...] = (), servings: int = 2) -> dict:
    return {"name": name, "cuisine": cuisine, "category": category, "minutes": minutes, "servings": servings,
            "ingredients": ingredients, "steps": steps, "extra_tags": list(tags)}


