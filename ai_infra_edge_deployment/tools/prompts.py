"""測定に使う固定のプロンプト集。

**毎回同じ入力で測る**ことが比較の前提。ここを変えたら過去の数字と比べられない。
みなと商事の社内ヘルプデスクへの問い合わせを想定している（シリーズ共通の題材）。
"""

from __future__ import annotations

SYSTEM_PREFIX = (
    "あなたは社内ヘルプデスクの回答者です。"
    "社内規程に基づき、簡潔に日本語で回答してください。\n\n"
)

QUESTIONS = [
    "有給休暇の申請はいつまでに出せばよいですか。",
    "交通費の精算の締切を教えてください。",
    "貸与PCが起動しなくなりました。どうすればよいですか。",
    "パスワードを忘れてロックされました。",
    "会議室は連続で何時間まで使えますか。",
    "不審なメールが届いた場合の報告先はどこですか。",
    "出張旅費はいつまでに精算しますか。",
    "多要素認証の登録期限を教えてください。",
    "備品を購入したいのですが、決裁は誰が行いますか。",
    "退職時にPCはいつ返却しますか。",
    "残業の事前申請の上限時間は何時間ですか。",
    "入退館カードを紛失した場合の手続きを教えてください。",
    "USBメモリは業務で使ってよいですか。",
    "代休はいつまでに取得する必要がありますか。",
    "外部サービスを業務で使いたい場合の申請方法は。",
    "郵便物の集配時刻を教えてください。",
    "打刻を忘れた場合はどう修正しますか。",
    "機密文書の保管期間はどれくらいですか。",
    "駐車場の月額利用料はいくらですか。",
    "育児休業の申出はいつまでに行いますか。",
]


def with_shared_prefix() -> list[str]:
    """共通のシステムプロンプトを先頭に付ける。

    先頭が揃っていると推論サーバの前方一致キャッシュが効く（セッション6の題材）。
    """
    return [SYSTEM_PREFIX + q for q in QUESTIONS]


def with_unique_prefix() -> list[str]:
    """あえて先頭を毎回変える。前方一致キャッシュが効かなくなる比較用。"""
    return [f"[req-{i:03d}] " + SYSTEM_PREFIX + q for i, q in enumerate(QUESTIONS)]
