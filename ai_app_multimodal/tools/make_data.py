def grams(name: str, amount: float, unit: str) -> float:
    allergens, kcal, units = INGREDIENTS[name]
    if unit in ("g", "ml"):
        return amount
    if unit not in units:
        raise KeyError(f"{name} の単位 {unit} の換算がありません")
    return amount * units[unit]


def build(rng: random.Random) -> tuple[list[dict], list[dict]]:
    names = [r["name"] for r in RECIPES]
    assert len(RECIPES) == 120, f"レシピは120件にする（現在 {len(RECIPES)} 件）"
    assert len(set(names)) == len(names), "レシピ名が重複しています"
    recipes = []
    for i, r in enumerate(RECIPES, start=1):
        ingredients = [{"name": n, "amount": a, "unit": u} for n, a, u in r["ingredients"]]
        for ing in ingredients:
            if ing["name"] not in INGREDIENTS:
                raise KeyError(f"{r['name']}: 食材表にない食材 {ing['name']}")
            if not ing["amount"] > 0:
                raise ValueError(f"{r['name']}: {ing['name']} の分量が 0 以下です")
        total_kcal = sum(grams(x["name"], x["amount"], x["unit"]) * INGREDIENTS[x["name"]][1] / 100 for x in ingredients)
        kcal = int(round(total_kcal / r["servings"] / 10) * 10)
        jitter = 0 if i == 1 else rng.choice([-5, 0, 0, 5])
        minutes = max(5, r["minutes"] + jitter)
        found = {a for x in ingredients for a in INGREDIENTS[x["name"]][0]}
        allergens = [a for a in ALLERGEN_ORDER if a in found]
        tags = [r["cuisine"], r["category"], *r["extra_tags"]]
        if minutes <= 15:
            tags.append("時短")
        if kcal <= 250 and r["category"] == "主菜":
            tags.append("ヘルシー")
        recipes.append({
            "id": f"R{i:03d}",
            "name": r["name"],
            "minutes": minutes,
            "kcal": kcal,
            "servings": r["servings"],
            "ingredients": [{**x, "amount": int(x["amount"]) if float(x["amount"]).is_integer() else x["amount"]} for x in ingredients],
            "steps": r["steps"],
            "tags": tags,
            "allergens": allergens,
        })
    users = [
        {"id": "u001", "name": "佐藤 美咲", "plan": "free", "household_size": 2, "allergies": [], "preferences": ["時短"]},
        {"id": "u002", "name": "鈴木 健太", "plan": "pro", "household_size": 4, "allergies": ["えび", "かに"], "preferences": ["お弁当", "作り置き"]},
        {"id": "u003", "name": "高橋 さくら", "plan": "free", "household_size": 3, "allergies": ["卵"], "preferences": ["和食"]},
        {"id": "u004", "name": "田中 大輔", "plan": "pro", "household_size": 1, "allergies": ["そば", "落花生"], "preferences": ["ヘルシー"]},
        {"id": "u005", "name": "伊藤 陽子", "plan": "free", "household_size": 5, "allergies": ["乳"], "preferences": ["作り置き", "洋食"]},
    ]
    for n, u in enumerate(users):
        u["created_at"] = f"2026-09-{n + 1:02d}T09:00:00+09:00"
    return recipes, users


def dump(value: object) -> bytes:
    return (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(Path(__file__).resolve().parent.parent / "data"))
    parser.add_argument("--check", action="store_true", help="書き出さずにハッシュだけ表示する")
    args = parser.parse_args()
    recipes, users = build(random.Random(SEED))
    out = Path(args.out)
    for name, value in (("recipes.json", recipes), ("users.json", users)):
        data = dump(value)
        if not args.check:
            out.mkdir(parents=True, exist_ok=True)
            (out / name).write_bytes(data)
        print(f"{name}\t{len(value)}件\tsha256:{hashlib.sha256(data).hexdigest()[:12]}")


if __name__ == "__main__":
    main()
