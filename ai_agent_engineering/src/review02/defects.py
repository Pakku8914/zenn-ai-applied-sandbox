#!/usr/bin/env python3
"""復習02：構造の欠陥5分類と、それを確かめる決定的なテストの対応表。

    docker compose exec app python src/review02/defects.py

復習01では「症状 → 原因」を軌跡から切り分けた。復習02で並べるのは別の軸である。
**同じ症状が出ていても、欠けているのは構造のどこか**を言い当てる語彙を持つ。

名前を5つに固定しておくのが要点である。名前が無いと、報告のたびに言葉が変わって
（「なんか状態がおかしい」「文脈が飛んだ」）蓄積できない。
"""

from __future__ import annotations

from _paths import setup

ROOT = setup()

# 欠陥の名前。表示順を固定する（人によって並びが変わると比較できない）
DEFECTS = (
    "状態を持っていない",
    "遷移を絞っていない",
    "副作用の前に意図を保存していない",
    "捨てる前に状態へ移していない",
    "自由文で引き継いだ",
)

# 欠陥 → (何が起きるか, どこを見れば分かるか, 手当てをする章, 確かめ方)
CATALOG = {
    "状態を持っていない": (
        "進捗を会話履歴の文字列から推測するので、再開のたびに位置がずれる",
        "履歴には「実行した」と「これから実行する」が同じ文字列で並んでいる",
        "S06",
        "src/session06/modes.py の history_only()：推測 drafting / 実際 collecting"),
    "遷移を絞っていない": (
        "段階を飛ばした操作が実行され、副作用が先に出る",
        "軌跡の早い位置に書き込み系のツールが成功している",
        "S06",
        "src/session06/verify.py：collecting では book_room を実行できない"),
    "副作用の前に意図を保存していない": (
        "実行の後・保存の前に落ちると、再開で同じ副作用がもう一度出る",
        "軌跡は同じなのに、データ側の行数が違う",
        "S06",
        "src/session06/durability.py の crash_matrix()：bookings 2 / 1 / 2 / 1"),
    "捨てる前に状態へ移していない": (
        "圧縮で判断材料が消え、再開しても同じ結論に到達できない",
        "履歴から古い項目が消えており、状態にも同じ情報が無い",
        "S07",
        "src/review02/memo.py の compare()：切り捨ては制約 0/3・事実 0/2"),
    "自由文で引き継いだ": (
        "前段が知っていた事実が次の体に伝わらず、避けられた失敗を踏む",
        "引き継ぎの文字列に、次の体が必要とする項目が入っていない",
        "S08",
        "src/review02/split.py の handoff_loss()：自由文 1/3 → 構造化 3/3"),
}

# 運用担当から来た報告（症状だけが書かれている。原因は書いていない）
INCIDENTS = {
    "INC-11": "途中で落ちたあと再開したら、会議室が2件予約されていました。"
              "軌跡はどちらも9手・done で、見比べても違いがありません。",
    "INC-12": "レポートを作る前に会議室が予約されていました。"
              "違反が0件だった案件でも部屋が押さえられています。",
    "INC-13": "長いタスクの後半で、最初に伝えた「5万円以上は事前承認」を無視した"
              "申請が出ました。履歴が長くなったので古い方から捨てる作りにしています。",
    "INC-14": "調査担当の報告をそのまま手配担当に渡したら、"
              "すでに埋まっている枠を選んで予約に失敗しました。",
    "INC-15": "再開のたびに最初の一手からやり直しになります。"
              "どこまで進んだかは会話履歴のテキストから読み取っています。",
}


def catalog_rows() -> list[dict]:
    return [{"欠陥": name, "何が起きるか": CATALOG[name][0],
             "どこを見るか": CATALOG[name][1], "手当て": CATALOG[name][2],
             "確かめ方": CATALOG[name][3]}
            for name in DEFECTS]


def main() -> None:
    print("=== 構造の欠陥5分類 ===")
    for row in catalog_rows():
        print(f"[{row['欠陥']}] 手当て: {row['手当て']}")
        print(f"  何が起きるか: {row['何が起きるか']}")
        print(f"  どこを見るか: {row['どこを見るか']}")
        print(f"  確かめ方    : {row['確かめ方']}")
    print()
    print("=== 障害報告（原因は書かれていない）===")
    for key, text in INCIDENTS.items():
        print(f"{key}: {text}")


if __name__ == "__main__":
    main()
