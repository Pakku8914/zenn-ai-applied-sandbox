-- 演習 S03-ex05: リーフ 1 枚のキー数から、リーフの枚数と木の高さを見積もる
-- リーフ: 一括構築では 90% まで詰める。使える 8152 バイト（8192 - ヘッダ 24 - 特殊領域 16）の 90% を
--         1 項目 20 バイト（16 + 行ポインタ 4）で割ると 366 件（＋ high key 1 件で 367）
-- 内部ページ: 70% まで詰めるので 8152 * 0.7 / 20 ≒ 285 件
SELECT floor(8152 * 0.9 / 20) AS leaf_items,
       floor(8152 * 0.7 / 20) AS internal_items;

-- 100 万件: リーフ 2733 枚 → 内部ページ 10 枚 → ルート 1 枚（高さ 3）
SELECT ceil(1000000 / 366.0)                   AS leaf_pages,
       ceil(ceil(1000000 / 366.0) / 285.0)     AS level1_pages;

-- 1 億件なら: リーフ 273,225 枚 → 内部 959 枚 → その上 4 枚 → ルート（高さ 4）
SELECT ceil(100000000 / 366.0)                               AS leaf_pages,
       ceil(ceil(100000000 / 366.0) / 285.0)                 AS level1_pages,
       ceil(ceil(ceil(100000000 / 366.0) / 285.0) / 285.0)   AS level2_pages;
